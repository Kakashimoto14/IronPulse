  function lerp(a, b, t) {
    return a + (b - a) * t;
  }

  function easeInOut(t) {
    return t < 0.5 ? 2 * t * t : 1 - Math.pow(-2 * t + 2, 2) / 2;
  }

  // Convert normalized cycle u in [0..1] into smooth rep curve (0 = start/extended, 1 = peak contraction)
  // Plus phase classification: ECCENTRIC / PEAK / CONCENTRIC / LOCKOUT
  function cycleWave(u) {
    var phase, p;
    if (u < 0.42) {
      phase = 'ECCENTRIC';
      p = easeInOut(u / 0.42);
    } else if (u < 0.55) {
      phase = 'PEAK TENSION';
      p = 1;
    } else if (u < 0.88) {
      phase = 'DRIVE / LOCKOUT';
      p = 1 - easeInOut((u - 0.55) / 0.33);
    } else {
      phase = 'RESET / BRACE';
      p = 0;
    }
    return { p: p, phase: phase };
  }

